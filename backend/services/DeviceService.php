<?php
// Readings from the astronaut's wearable (the OrbitCare vest — for now its Wokwi simulation).
//
// How a reading travels:
//   ESP32 → POST /api/device/readings (X-Device-Token) → device_readings (kept exactly as sent)
//         → heart rate, SpO2 and respiratory rate are validated and stored as raw_measurements of a
//           live stream → the same analysis, alert engine and crew alarm as recorded data.
//
// A live stream is a source_records row ("device-sim:<device>" or "device:<device>") played at
// speed 1 from the moment the stream started, so a reading's place in the stream is the time it
// reached OrbitCare. The device's own clock is kept in device_readings.device_timestamp.
// Readings that arrive more than LATE_SECONDS after the device measured them, or in a burst less
// than half a sample interval after the previous one (the device emptying its offline queue), are
// stored but not analysed: an alert built from old values would be misleading, and analysis must
// stay in time order with one sample per interval.
//
// Not analysed (stored as sent, no alerts): blood pressure, CO2, radiation, skin temperature and
// motion — OrbitCare has no sourced limits for them yet, and in the simulation CO2/radiation are
// generated by the firmware, not measured.
declare(strict_types=1);

final class DeviceService
{
    // Payload field → BIDMC column whose validation limits (physically possible values) apply.
    public const VITALS = ['heart_rate_bpm' => 'HR', 'spo2_percent' => 'SpO2', 'respiratory_rate_bpm' => 'RESP'];
    public const SOURCE_SIMULATED = 'OrbitCare vest simulation (Wokwi) — simulated values';
    public const SOURCE_HARDWARE = 'OrbitCare vest sensors';
    public const SAMPLE_SECONDS = 5;          // the firmware sends one reading every 5 s (SEND_MS = 5000)
    private const LATE_SECONDS = 30;
    private const STREAM_SECONDS = 2592000;   // a live stream lasts up to 30 days, then a new one starts

    /** @var Closure(): float  current time (tests pass a fake clock) */
    private Closure $clock;

    public function __construct(
        private DataValidator $validator = new DataValidator(),
        private DataReplay $replay = new DataReplay(),
        ?Closure $clock = null
    ) {
        $this->clock = $clock ?? fn (): float => microtime(true);
    }

    /** Binds a device to an astronaut. Returns the device row and its token (shown once, never stored). */
    public function register(int $astronautId, string $deviceId, string $kind = 'simulated'): array
    {
        if (!preg_match('/^[A-Za-z0-9_.-]{3,64}$/', $deviceId)) {
            throw new InvalidArgumentException('Device ID: 3–64 letters, digits, "_", "-" or ".".');
        }
        if (!in_array($kind, ['simulated', 'hardware'], true)) {
            throw new InvalidArgumentException('Kind must be "simulated" or "hardware".');
        }
        $astronaut = db()->prepare("SELECT 1 FROM users u JOIN astronauts a ON a.user_id = u.id WHERE u.id = ? AND u.role = 'astronaut'");
        $astronaut->execute([$astronautId]);
        if (!$astronaut->fetchColumn()) {
            throw new InvalidArgumentException('That account is not an astronaut.');
        }

        $token = 'ocd_' . bin2hex(random_bytes(24));
        db()->prepare('INSERT INTO devices (device_id, user_id, token_hash, kind) VALUES (?, ?, ?, ?)')
            ->execute([$deviceId, $astronautId, hash('sha256', $token), $kind]);
        $id = (int) db()->lastInsertId();
        audit('device.register', $astronautId, 'device', (string) $id, ['device_id' => $deviceId, 'kind' => $kind]);
        return ['device' => $this->find($id), 'token' => $token];
    }

    // The device that owns this token, or 401.
    public function authenticate(?string $token): array
    {
        $token = trim((string) $token);
        if ($token !== '') {
            $statement = db()->prepare('SELECT * FROM devices WHERE token_hash = ? AND revoked_at IS NULL');
            $statement->execute([hash('sha256', $token)]);
            if ($device = $statement->fetch()) {
                return $device;
            }
        }
        throw new ApiException(401, 'device_unauthorized', t('err.device_unauthorized'));
    }

    public function ingest(array $device, array $body): array
    {
        $readingId = $body['client_reading_id'] ?? null;
        if (!is_string($readingId) || !preg_match('/^[A-Za-z0-9_.:-]{1,80}$/', $readingId)) {
            throw ApiException::validation(['client_reading_id' => t('err.device_reading_id')]);
        }
        $this->checkAstronaut($device, $body['astronaut_id'] ?? null);

        $received = ($this->clock)();
        $deviceTime = $this->deviceTime($body['timestamp'] ?? null);

        // Claim the reading first (unique per device): a retried POST is not stored or analysed twice.
        $claim = db()->prepare(
            'INSERT IGNORE INTO device_readings (device_pk, client_reading_id, received_at, device_timestamp, payload) VALUES (?, ?, ?, ?, ?)'
        );
        $claim->execute([$device['id'], $readingId, $this->formatTime($received), $deviceTime !== null ? gmdate('Y-m-d H:i:s', (int) $deviceTime) : null,
            json_encode($body, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES)]);
        if ($claim->rowCount() === 0) {
            return ['status' => 'duplicate'];
        }
        $readingPk = (int) db()->lastInsertId();
        db()->prepare('UPDATE devices SET last_seen_at = ? WHERE id = ?')->execute([$this->formatTime($received), $device['id']]);

        [$values, $rejected] = $this->vitals($body);
        $notAnalysed = array_values(array_diff(array_keys($body), array_keys(self::VITALS), ['client_reading_id', 'device_id', 'astronaut_id', 'timestamp', 'uptime_ms', 'signal_quality', 'data_source']));

        if ($deviceTime !== null && $received - $deviceTime > self::LATE_SECONDS) {
            $status = 'late';
            $recordId = null;
        } elseif (!$values) {
            $status = 'no_vitals';
            $recordId = null;
        } else {
            $recordId = $this->store($device, $values);
            $status = $recordId !== null ? 'analysed' : 'late';
        }
        db()->prepare('UPDATE device_readings SET status = ?, record_id = ? WHERE id = ?')->execute([$status, $recordId, $readingPk]);
        log_event('device.reading', ['device_pk' => (int) $device['id'], 'user_id' => (int) $device['user_id'], 'status' => $status, 'metrics' => count($values)]);

        return [
            'status' => $status,
            'analysed' => array_keys($values),
            'rejected' => $rejected,
            'stored_not_analysed' => $notAnalysed,
        ];
    }

    // ---------- internals ----------

    private function find(int $id): array
    {
        $statement = db()->prepare('SELECT id, device_id, user_id, kind, current_record_id, created_at FROM devices WHERE id = ?');
        $statement->execute([$id]);
        return $statement->fetch();
    }

    // The payload may name the astronaut (code); it must be the one the device is bound to.
    private function checkAstronaut(array $device, mixed $code): void
    {
        if ($code === null || $code === '') {
            return;
        }
        $statement = db()->prepare('SELECT astronaut_code FROM astronauts WHERE user_id = ?');
        $statement->execute([$device['user_id']]);
        if (!is_string($code) || strcasecmp($code, (string) $statement->fetchColumn()) !== 0) {
            throw ApiException::validation(['astronaut_id' => t('err.device_astronaut_mismatch')]);
        }
    }

    // ISO-8601 UTC time from the device clock, or null when missing / not a sane time.
    private function deviceTime(mixed $value): ?float
    {
        if (!is_string($value) || $value === '') {
            return null;
        }
        try {
            $time = (float) (new DateTimeImmutable($value))->format('U.u');
        } catch (Exception $error) {
            return null;
        }
        return $time > 1700000000 && $time < ($this->clock)() + 300 ? $time : null;
    }

    /** @return array{0: array<string, array{value: float, unit: string}>, 1: string[]} valid vitals by metric, rejected field names */
    private function vitals(array $body): array
    {
        $values = [];
        $rejected = [];
        foreach (self::VITALS as $field => $column) {
            if (!array_key_exists($field, $body) || $body[$field] === null) {
                continue;
            }
            $raw = $body[$field];
            $check = is_int($raw) || is_float($raw) ? $this->validator->validateValue($column, (string) $raw) : ['status' => 'invalid'];
            if ($check['status'] === 'valid') {
                $rule = DataValidator::COLUMNS[$column];
                $values[$rule['metric']] = ['value' => $check['value'], 'unit' => $rule['unit']];
            } else {
                $rejected[] = $field;
            }
        }
        return [$values, $rejected];
    }

    // Appends the vitals to the astronaut's live stream and runs the normal analysis on them.
    // Returns the stream's record ID, or null for a burst reading (stored in device_readings only).
    private function store(array $device, array $values): ?string
    {
        $session = $this->liveSession($device);
        $stored = db_transaction(function (PDO $pdo) use ($session, $values): bool {
            // Locked like DataReplay::advance, so a reading is never placed behind what was already analysed.
            $lock = $pdo->prepare('SELECT started_at, last_processed_offset FROM replay_sessions WHERE id = ? FOR UPDATE');
            $lock->execute([$session['id']]);
            $state = $lock->fetch();
            $last = $pdo->prepare('SELECT COALESCE(MAX(original_timestamp), -1), COALESCE(MAX(source_row), 0) FROM raw_measurements WHERE source_record_id = ?');
            $last->execute([$session['source_record_id']]);
            [$lastOffset, $lastRow] = $last->fetch(PDO::FETCH_NUM);

            $elapsed = ($this->clock)() - (float) (new DateTimeImmutable($state['started_at'], new DateTimeZone('UTC')))->format('U.u');
            if ((float) $lastOffset >= 0 && $elapsed - (float) $lastOffset < self::SAMPLE_SECONDS / 2) {
                return false;   // a burst from the device's queue, not a new sample
            }
            // Rounded DOWN to the millisecond (the column's precision), so the reading is never placed
            // past the analysis position computed from the same clock; and always after what was already analysed.
            $offset = max(floor($elapsed * 1000) / 1000, round((float) $lastOffset + 0.001, 3), round((float) $state['last_processed_offset'] + 0.001, 3));

            $insert = $pdo->prepare(
                'INSERT INTO raw_measurements (source, source_record_id, source_file, source_row, original_timestamp, metric, value, unit) VALUES (?, ?, ?, ?, ?, ?, ?, ?)'
            );
            foreach ($values as $metric => $reading) {
                $insert->execute([$session['source'], $session['source_record_id'], $session['source_file'], (int) $lastRow + 1, $offset, $metric, $reading['value'], $reading['unit']]);
            }
            $pdo->prepare('UPDATE source_records SET rows_read = rows_read + 1, values_stored = values_stored + ? WHERE record_id = ?')
                ->execute([count($values), $session['source_record_id']]);
            return true;
        });
        if (!$stored) {
            return null;
        }
        $this->replay->advance((int) $session['id'], ($this->clock)());
        return $session['source_record_id'];
    }

    // The device's running live stream, or a new one (which becomes the astronaut's data source).
    private function liveSession(array $device): array
    {
        $stream = db()->prepare('SELECT current_record_id FROM devices WHERE id = ?');
        $stream->execute([$device['id']]);
        $streamId = $stream->fetchColumn();
        $current = $this->replay->currentSession((int) $device['user_id']);
        if ($current && $current['status'] === 'running' && $streamId !== null && $current['source_record_id'] === $streamId) {
            return $current;
        }

        $simulated = $device['kind'] === 'simulated';
        $recordId = sprintf('dev%d-%s', $device['id'], gmdate('ymdHis'));
        db()->prepare(
            'INSERT INTO source_records (record_id, source, source_file, duration_seconds, sample_interval_seconds, rows_read, values_stored, values_missing, values_rejected)
             VALUES (?, ?, ?, ?, ?, 0, 0, 0, 0)'
        )->execute([$recordId, $simulated ? self::SOURCE_SIMULATED : self::SOURCE_HARDWARE, ($simulated ? 'device-sim:' : 'device:') . $device['device_id'],
            self::STREAM_SECONDS, self::SAMPLE_SECONDS]);
        db()->prepare('UPDATE devices SET current_record_id = ? WHERE id = ?')->execute([$recordId, $device['id']]);
        db()->prepare('UPDATE astronauts SET data_source_record_id = ? WHERE user_id = ?')->execute([$recordId, $device['user_id']]);
        log_event('device.stream_started', ['device_pk' => (int) $device['id'], 'user_id' => (int) $device['user_id'], 'record_id' => $recordId]);
        return $this->replay->start((int) $device['user_id'], $recordId, ($this->clock)(), 1.0);
    }

    private function formatTime(float $timestamp): string
    {
        return DateTimeImmutable::createFromFormat('U.u', sprintf('%.6F', $timestamp), new DateTimeZone('UTC'))->format('Y-m-d H:i:s.v');
    }
}
